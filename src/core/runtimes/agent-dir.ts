/**
 * The built-in agent-dir runtime, as seen by compose.
 *
 * When a deployment declares no `runtime`, the framework runs a small headless
 * Genkit app that loads the project's `agents/` folder via the `agent-dir`
 * helper. Rather than invent a new packaging path, compose *synthesizes* that
 * app into the staging `user/` dir as an ordinary JS runtime: an `index.mjs`
 * that calls `loadAgentDir` plus a `package.json` with the needed deps, and a
 * copy of the agents folder. Everything downstream (js dockerfile, single vs
 * sidecar packaging, `--local`) then treats it like any other JS app.
 */

import fs from 'fs';
import path from 'path';
import { linkLocalLibrary } from '../../util/local-library';
import type { AgentDirConfig, ResolvedRuntime } from '../types';
import { jsRuntime } from './js';

/** The library version range the synthesized app depends on. */
const RUNTIME_DEPS: Record<string, string> = {
  '@genkit-ai/anthropic': '^0.4.0',
  '@genkit-ai/compat-oai': '^1.41.0',
  '@genkit-ai/google-genai': '^1.41.0',
  '@genkit-ai/middleware': '^0.9.0',
  genkit: '^1.40.1',
  'genkit-channels': '^0.1.0',
};

/** Resolves the built-in runtime to a JS runtime rooted at the staged app. */
export function resolveAgentDirRuntime(): ResolvedRuntime {
  // A plain JS app: `node index.mjs`, built with `npm install`. The js builder
  // gives us the Dockerfile plan (copy the whole user dir) for free.
  return jsRuntime.resolve({
    language: 'js',
    command: 'node',
    args: ['index.mjs'],
    build: 'npm install',
    cwd: '.',
  });
}

/**
 * Writes the synthesized agent-dir app into `userDest` (the staging `user/`
 * dir): `index.mjs`, `package.json`, and a copy of the resolved agents folder.
 * Returns the absolute agents dir that was copied (for logging).
 */
export function synthesizeAgentDirApp(
  projectDir: string,
  userDest: string,
  agents: AgentDirConfig | undefined
): { agentsDir: string; agentCount: number } {
  const agentsRel = agents?.dir ?? './agents';
  const agentsSrc = path.resolve(projectDir, agentsRel);
  const model = agents?.model;

  fs.mkdirSync(userDest, { recursive: true });

  // Copy the agents folder into the app as ./agents.
  const agentsDest = path.join(userDest, 'agents');
  let agentCount = 0;
  if (fs.existsSync(agentsSrc)) {
    copyDir(agentsSrc, agentsDest);
    agentCount = fs
      .readdirSync(agentsDest, { withFileTypes: true })
      .filter((e) => e.isDirectory() && !e.name.startsWith('.')).length;
  } else {
    fs.mkdirSync(agentsDest, { recursive: true });
  }

  // The headless entry: load the agent dir and idle so the reflection v2 client
  // (started by genkit() in dev env) connects back to the channel.
  const indexBody =
    `// Generated by genkit-channels: the built-in agent-dir runtime.\n` +
    `import { loadAgentDir } from 'genkit-channels/agent-dir';\n\n` +
    `loadAgentDir({ dir: './agents'${
      model ? `, defaultModel: ${JSON.stringify(model)}` : ''
    } });\n` +
    `console.log('[agent-dir] runtime up');\n` +
    `setInterval(() => {}, 1 << 30);\n`;
  fs.writeFileSync(path.join(userDest, 'index.mjs'), indexBody);


  // A minimal package.json so `npm install` pulls the runtime deps.
  const pkg = {
    name: 'genkit-channels-agent-dir-app',
    private: true,
    version: '0.0.0',
    type: 'module',
    dependencies: { ...RUNTIME_DEPS },
  };
  const pkgPath = path.join(userDest, 'package.json');
  fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + '\n');
  // Until genkit-channels is published, point the dep at this checkout so
  // `npm install` can resolve it (a no-op once published).
  linkLocalLibrary(pkgPath);

  return { agentsDir: agentsSrc, agentCount };
}

/** Recursively copies a directory, skipping node_modules and dotdirs. */
function copyDir(src: string, dest: string): void {
  fs.mkdirSync(dest, { recursive: true });
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    if (entry.name === 'node_modules') continue;
    const s = path.join(src, entry.name);
    const d = path.join(dest, entry.name);
    if (entry.isDirectory()) {
      copyDir(s, d);
    } else {
      fs.copyFileSync(s, d);
    }
  }
}
